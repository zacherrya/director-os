export function Icon({
  name,
  className,
  size = 16,
  style,
}: {
  name: string
  className?: string
  size?: number
  style?: CSSProperties
}) {
  const Cmp = registry[name] ?? Sparkles
  return <Cmp className={className} size={size} strokeWidth={1.75} style={style} />
}

